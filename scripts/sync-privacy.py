#!/usr/bin/env python3
"""Generate native offline policy text and the public copy from the bundled HTML."""
import json
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

class PolicyParser(HTMLParser):
    def __init__(self):
        super().__init__()
        self.active = False
        self.tag = None
        self.parts = []
        self.sections = []

    def handle_starttag(self, tag, attrs):
        if tag == "section" and dict(attrs).get("id") == "privacidad":
            self.active = True
        if self.active and tag in ("h2", "p"):
            self.tag, self.parts = tag, []

    def handle_data(self, data):
        if self.active and self.tag:
            self.parts.append(data)

    def handle_endtag(self, tag):
        if self.active and tag == self.tag:
            text = "".join(self.parts).strip()
            if tag == "h2":
                self.sections.append([text, []])
            else:
                self.sections[-1][1].append(text)
            self.tag = None
        if tag == "section":
            self.active = False

source = ROOT / "Vaquita/privacidad.html"
parser = PolicyParser()
parser.feed(source.read_text())
quote = lambda s: json.dumps(s, ensure_ascii=False)
lines = ["// Generated by scripts/sync-privacy.py from privacidad.html. Do not edit by hand.",
         "import Foundation", "struct SeccionPrivacidad {", "    let titulo: String", "    let texto: String", "}",
         "enum PoliticaPrivacidad {", "    static let secciones: [SeccionPrivacidad] = ["]
for title, paragraphs in parser.sections:
    lines.append(f"        SeccionPrivacidad(titulo: String(localized: {quote(title)}), texto: String(localized: {quote(chr(10).join(paragraphs))})),")
lines += ["    ]", "}"]
(ROOT / "Vaquita/PoliticaPrivacidad.swift").write_text("\n".join(lines) + "\n")
(ROOT / "Distribution/privacidad.html").write_text(source.read_text())
